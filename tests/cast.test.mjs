import fs from 'fs';
import vm from 'vm';
const sandbox = { window: {} };
vm.runInContext(fs.readFileSync(new URL('../js/cast.js', import.meta.url), 'utf8'), vm.createContext(sandbox));
const C = sandbox.window.CAST;
let bad = 0;
const ok = (n, c, extra) => { if (!c) { bad++; console.error('FAIL', n, extra === undefined ? '' : JSON.stringify(extra)); } else console.log('ok', n); };
ok('age 17 rejected', !!C.build({ age: 17, bg: 'bit' }).error);
ok('age 18 accepted', !C.build({ age: 18, bg: 'fresh', gender: 'f', pref: 'any' }).error);
ok('age 70 accepted', !C.build({ age: 70, bg: 'bit', gender: 'm' }).error);
ok('age 71 rejected', !!C.build({ age: 71 }).error);
ok('fraction rejected', !!C.build({ age: 20.5 }).error);
const woman = C.build({ age: 40, bg: 'kitchen', gender: 'f', pref: 'm', name: '阿青' }).identity;
const man = C.build({ age: 40, bg: 'kitchen', gender: 'm', pref: 'f', name: '阿青' }).identity;
ok('gender does not change starting numbers', woman.stats.stamina === man.stats.stamina && woman.skills.knife === man.skills.knife && woman.startMoney === man.startMoney && woman.female !== man.female);
ok('background changes skills', C.build({ age: 30, bg: 'books' }).identity.skills.eye > C.build({ age: 30, bg: 'fresh' }).identity.skills.eye);
const older = C.build({ age: 62, bg: 'errand' }).identity;
ok('older start is still a workable shift', older.stats.stamina >= 78 && older.maxStamina >= 90);
ok('town name rejected', !!C.build({ age: 30, name: '马驹桥' }).error);
const save = { money: 500, earned: 2500, life: { partner: { state: 'married', name: '旧人' } } };
C.migrateSave(save);
ok('migration uses recorded earnings and does not invent a second book', save.wageBook === 2500 && save.wageFromEarned === true);
const first = C.claim(save);
ok('crossed milestones grant once', first.map(m => m.id).join() === 'm1000,m2000');
const moneyAfter = save.money;
C.claim(save);
ok('reload does not grant again', save.money === moneyAfter && C.claim(save).length === 0);
ok('deposit is not earnings', C.note(save, 800, 'deposit') === 2500);
ok('loan is not earnings', C.note(save, 500, 'loan') === 2500);
C.note(save, 500, 'job');
ok('new wages advance the book', save.wageBook === 3000);
const prize = C.claim(save).find(m => m.id === 'm3000');
ok('3000 reward is separate from the book', !!prize && prize.money === 40);
save.money += prize.money;
ok('reward cash is not fed back into the book', C.note(save, prize.money, 'reward') === 3000 && save.wageBook === 3000);
const social = { social: { pref: 'any', people: {} }, life: {} };
const a = C.chat(social, 'hejie');
const beforeB = C.relOf(social, 'acheng').affection;
ok('friendship does not raise romance', a.affection === 0 && C.relOf(social, 'acheng').friend === 0 && C.relOf(social, 'acheng').affection === beforeB);
let taught = null;
for (let i = 0; i < 8 && !taught; i++) taught = C.chat(social, 'hejie').teach;
ok('friendship teaches a real skill once', taught && taught.skill === 'knife' && taught.xp === 12 && !C.chat(social, 'hejie').teach);
const none = { social: { pref: 'none', people: {} } };
ok('no preference blocks romance', C.court(none, 'acheng', 30).error === 'pref');
ok('stated preference is not implied by gender', C.court({ social: { pref: 'f', people: {} } }, 'acheng', 30).error === 'pref');
const open = { social: { pref: 'any', people: {} }, life: {} };
C.court(open, 'hejie', 28);
C.court(open, 'acheng', 28);
ok('two people can be known at once', open.social.people.hejie.bond === 'interested' && open.social.people.acheng.bond === 'interested');
for (let i = 0; i < 10; i++) C.court(open, 'hejie', 28);
const dated = C.commit(open, 'hejie');
ok('commitment is explicit', dated.ok && dated.partner.state === 'dating' && dated.partner.fromCast === 'hejie');
ok('a second commitment is refused', C.commit(open, 'acheng').error === 'taken');
ok('friendship continues beside a commitment', C.chat(open, 'acheng').ok && open.social.people.acheng.bond === 'interested');
ok('existing marriage blocks a new commitment', C.commit(save, 'linwan').error === 'taken');
ok('minor player cannot court', C.court({ social: { pref: 'any', people: {} } }, 'linwan', 17).error === 'minor');
const attrs = { phone: 3 }, flags = {};
ok('phone improves once a day', C.practicePhone(attrs, flags, 2).practiced && attrs.phone === 4 && !C.practicePhone(attrs, flags, 2).practiced);
if (bad) { console.error(bad + ' failed'); process.exit(1); }
console.log('cast checks passed');
