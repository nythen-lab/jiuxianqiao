import fs from 'fs';
import vm from 'vm';
const code = fs.readFileSync(new URL('../js/shows.js', import.meta.url), 'utf8');
const sandbox = { window: {} };
vm.createContext(sandbox);
vm.runInContext(code, sandbox);
const S = sandbox.window.SHOWS;
let bad = 0;
const ok = (n, c, extra) => { if (!c) { bad++; console.error('FAIL', n, extra || ''); } else console.log('ok', n); };
const w = S.bathPick('wash', 0), so = S.bathPick('soak', 0), r = S.bathPick('rub', 1);
ok('bath sequences differ', w.key !== so.key && so.key !== r.key && w.steps.join() !== so.steps.join() && so.steps.join() !== r.steps.join());
ok('bath sounds differ', new Set([w.sound, so.sound, r.sound]).size === 3);
let st = null;
st = S.flipNote(st, 1, 'a');
const again = S.flipNote(st, 1.1, 'a');
ok('duplicate scold does not stack', again.appliedNow === false && again.toll === st.toll && again.toll === 2);
const later = S.flipNote(st, 2, 'b');
ok('second real mistake escalates', later.appliedNow && later.toll > st.toll && later.line !== st.lastLine);
let toll = later;
for (let i = 0; i < 8; i++) toll = S.flipNote(toll, 10 + i, 'n' + i);
ok('mental toll capped at 12', toll.toll <= 12, toll.toll);
const boot = S.fortuneBoot(false);
let held = boot;
for (let i = 0; i < 140; i++) held = S.fortuneStep(held, 1 / 60, { hold: 1 });
ok('hold shakes a stick out', held.fell === true, held.energy);
const taps = S.fortuneBoot(false);
let t = taps;
for (let i = 0; i < 3; i++) t = S.fortuneStep(t, 0.05, { tap: 1 });
ok('three light taps do not finish', t.fell !== true);
ok('kinds', S.actKind('scrap') === 'earn' && S.actKind('fishsell') === 'earn' && S.actKind('gig:dish') === 'earn');
ok('spend', S.actKind('bath:soak') === 'spend' && S.actKind('temple:oil') === 'spend' && S.actKind('fishgive') === 'spend');
ok('free', S.actKind('temple:bow') === 'free' && S.actKind('rest') === 'free' && S.actKind('sleep:street') === 'free' && S.actKind('sleep:home') === 'free' && S.actKind('sleep:month') === 'free' && S.actKind('gomoku') === 'free');
ok('paid bed is spend', S.actKind('sleep:upper') === 'spend' && S.actKind('sleep:netbar') === 'spend');
ok('money not income', S.actKind('bankbook') === 'money' && S.actKind('send') === 'money' && S.actKind('borrow') === 'money');
ok('risk and chore', S.actKind('scratch') === 'risk' && S.actKind('netsurf') === 'spend' && S.actKind('oddjob') === 'chore' && S.actKind('agency:healthCert') === 'chore');
const day = {};
const once = S.fortuneCommit(day, 20);
ok('fortune charges once', once.ok && once.money === 17 && once.charged);
const twice = S.fortuneCommit(day, once.money);
ok('fortune retry does not charge', twice.err === 'already' && twice.money === 17 && twice.charged === false);
const broke = {};
ok('broke fortune does not set the flag', S.fortuneCommit(broke, 2).err === 'money' && !broke.fortune);
if (bad) { console.error(bad + ' failed'); process.exit(1); }
console.log('shows checks passed');
